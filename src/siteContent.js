function mergeContent(base, override) {
  if (!override || typeof override !== "object") return base;
  if (Array.isArray(base)) return Array.isArray(override) ? override : base;
  return Object.fromEntries(
    Object.entries(base).map(([key, value]) => [
      key,
      value && typeof value === "object" && !Array.isArray(value)
        ? mergeContent(value, override[key])
        : override[key] ?? value,
    ]),
  );
}

export function loadSiteContent() {
  try {
    return mergeContent(DEFAULT_SITE_CONTENT, JSON.parse(localStorage.getItem(SITE_CONTENT_KEY) || "{}"));
  } catch (e) {
    return DEFAULT_SITE_CONTENT;
  }
}

export function saveSiteContent(content) {
  localStorage.setItem(SITE_CONTENT_KEY, JSON.stringify(content));
}

export function resetSiteContent() {
  localStorage.removeItem(SITE_CONTENT_KEY);
  return DEFAULT_SITE_CONTENT;
}
